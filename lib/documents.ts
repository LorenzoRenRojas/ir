export function generateDocument(type: string, company: CompanyData, context?: { title?: string; agency?: string }): string {
  switch (type) {
    case 'capability_statement':
      return generateCapabilityStatement(company)
    case 'letter_of_intent':
      return generateLetterOfIntent(company, context?.title, context?.agency)
    case 'past_performance':
      return generatePastPerformanceSummary(company)
    case 'rfi_response':
      return generateRFIResponse(company, context?.title)
    case 'teaming_agreement':
      return generateTeamingAgreement(company)
    default:
      return 'Unknown document type'
  }
}
